"""Benchmark: lint / format / complexity throughput on generated SQL.

Produces benchmarks/results.json and benchmarks/RESULTS.md. Every performance
number the README quotes comes from this script:

    python benchmarks/run.py

The workload is generated deterministically (fixed seed) so the table is
comparable between runs on the same machine.
"""

from __future__ import annotations

import json
import pathlib
import platform
import random
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from sql_lens import format_sql, lint_text, score_text  # noqa: E402

OUT_JSON = ROOT / "benchmarks" / "results.json"
OUT_MD = ROOT / "benchmarks" / "RESULTS.md"
SEED = 20261123
BT = chr(96)

TEMPLATES = [
    """select c.id, c.email, o.total_cents
from customers c
join orders o on o.customer_id = c.id
where c.created_at > now() - interval '{days} days'
  and o.status = '{status}'
  and lower(c.email) like '%@example.com'
order by o.created_at desc""",
    """update accounts
set locked = {flag}, locked_at = now()
where id in (select id from accounts where last_seen < now() - interval '{days} days')""",
    """with recent as (
    select id, customer_id, total_cents from orders where created_at > now() - interval '{days} days'
)
select r.customer_id, count(*) as orders, sum(r.total_cents) as revenue
from recent r
group by r.customer_id
having count(*) > 2
order by revenue desc""",
    """select o.id, (select count(*) from orders x where x.customer_id = o.customer_id) as n
from orders o
where o.total_cents between 1000 and {limit}""",
]

STATUSES = ["new", "paid", "shipped", "cancelled"]


def build_workload(target_bytes: int, seed: int = SEED) -> str:
    """Generate a deterministic SQL file of at least *target_bytes*."""
    rng = random.Random(seed)
    chunks: list[str] = []
    size = 0
    while size < target_bytes:
        template = TEMPLATES[len(chunks) % len(TEMPLATES)]
        statement = template.format(
            days=rng.randint(1, 365),
            status=rng.choice(STATUSES),
            flag="true" if rng.random() < 0.5 else "false",
            limit=rng.randint(10000, 90000),
        )
        chunks.append(statement.strip() + ";")
        size += len(statement) + 1
    return "\n\n".join(chunks) + "\n"


def timed(func, *args, repeat: int = 2) -> tuple[float, object]:
    """Return (best wall-clock seconds, result)."""
    best = float("inf")
    result = None
    for _ in range(repeat):
        start = time.perf_counter()
        result = func(*args)
        elapsed = time.perf_counter() - start
        best = min(best, elapsed)
    return best, result


def main() -> int:
    rows = []
    for label, target in (("100 KB", 100 * 1024), ("500 KB", 500 * 1024), ("1 MB", 1024 * 1024)):
        sql = build_workload(target)
        size_kb = len(sql.encode("utf-8")) / 1024
        lint_seconds, report = timed(lint_text, sql, "workload.sql")
        fmt_seconds, formatted = timed(format_sql, sql)
        cx_seconds, complexity = timed(score_text, sql, "postgres", "workload.sql")
        rows.append(
            {
                "input": label,
                "bytes": len(sql.encode("utf-8")),
                "statements": sql.count(";"),
                "lint_seconds": round(lint_seconds, 3),
                "lint_mb_per_s": round(size_kb / 1024 / lint_seconds, 2),
                "findings": len(report.findings),
                "format_seconds": round(fmt_seconds, 3),
                "format_mb_per_s": round(size_kb / 1024 / fmt_seconds, 2),
                "complexity_seconds": round(cx_seconds, 3),
                "queries_scored": len(complexity.queries),
                "format_idempotent": format_sql(formatted) == formatted,
            }
        )

    payload = {
        "tool": "sql-lens",
        "python": platform.python_version(),
        "platform": f"{platform.system()} {platform.release()}",
        "seed": SEED,
        "repeat": 2,
        "taken": "best of 2 wall-clock runs",
        "rows": rows,
    }
    OUT_JSON.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    header = (
        "| input | statements | findings | lint | lint MB/s | format | format MB/s | "
        "complexity | idempotent |\n"
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n"
    )
    body = ""
    for row in rows:
        body += (
            f"| {row['input']} | {row['statements']} | {row['findings']} | "
            f"{row['lint_seconds']:.3f} s | {row['lint_mb_per_s']:.1f} | "
            f"{row['format_seconds']:.3f} s | {row['format_mb_per_s']:.1f} | "
            f"{row['complexity_seconds']:.3f} s | {'yes' if row['format_idempotent'] else 'no'} |\n"
        )
    md = (
        "# Benchmark results\n\n"
        f"Generated by {BT}python benchmarks/run.py{BT} on {platform.system()} "
        f"{platform.release()}, Python {platform.python_version()}.\n"
        "Each measurement is the best of two wall-clock runs; the workload is "
        "generated deterministically from a fixed seed.\n\n"
        + header
        + body
        + "\nInput sizes are UTF-8 bytes of the generated SQL workload.\n"
    )
    OUT_MD.write_text(md, encoding="utf-8")
    print(md)
    print(f"wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())